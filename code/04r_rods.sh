stage subsetrods 1 0 do_subsetrods
stage class2drods "$NCPU" "$NGPU" do_class2drods
stage viewrods 1 0 do_viewrods
if [[ -n "${DO_SEL:-}" ]]; then
  stage selrods 1 0 do_selrods
  stage class2dsel "$NCPU" "$NGPU" do_class2dsel
