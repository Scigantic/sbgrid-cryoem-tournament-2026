# RELION's pickers do not find these rods; rodpick.py (run on the login node, free) does.
# When its output is present, skip the RELION picking stages.
if [[ -s RodsPick/rods.star ]]; then
  echo "rods from rodpick.py: $(grep -c '_rods.star' RodsPick/rods.star) micrographs"
  touch .done/templates .done/pickrods .done/census
fi
stage templates 1 0 do_templates
stage pickrods "$NCPU" "$NGPU" do_pickrods
stage census 1 0 do_census
