    --K "$K2D2" --iter "$ITER2D2" --tau2_fudge 2 --particle_diameter "$REFDIAM" \
    --flatten_solvent --zero_mask --center_classes --oversampling 1 --psi_step 5 \
    --offset_range 6 --offset_step 2 --norm --scale --dont_combine_weights_via_disc \
    --pool 30 --pad 2 --ctf --j "$THREADS_GPU" --gpu "$GPUARG" --preread_images
  python3 -I "$HERE/view_classes.py" "Class2D2/${LAST2D2}_model.star" \
    "Class2D2/${LAST2D2}_classes.mrcs" Class2D2/top_classes.jpg "$K2D2"
}

do_ini2() {
  mkdir -p Ini2
  relion_refine --i Extract2/particles.star --o Ini2/run --denovo_3dref --grad \
    --iter "$ITERINI2" --K 1 --sym C1 --ctf --particle_diameter "$REFDIAM" \
    --flatten_solvent --zero_mask --dont_combine_weights_via_disc --pool 30 --pad 1 \
    --skip_gridding --oversampling 1 --healpix_order 1 --offset_range 6 --offset_step 2 \
    --auto_sampling --tau2_fudge 4 --grad_write_iter 10 --j "$NCPU" --gpu "$GPUARG" \
    --preread_images
  python3 -I "$HERE/view3d.py" "Ini2/${LASTI2}_model.star" Ini2/model.jpg "$RISE"
}

