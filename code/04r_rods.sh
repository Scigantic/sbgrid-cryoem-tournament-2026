# Masked refinement. Refine3 reached 9.3 A after postprocessing but its own (unmasked)
# resolution estimate stalled at 20 A, because a 170 x 50 A rod fills under 2% of a 300 A
# box and solvent noise dominates the unmasked FSC; auto-refine then stopped after a few
# iterations. Give it a soft solvent mask and let it judge convergence on the masked FSC.
# Then a 3D classification without alignment from the refined poses, to split the rods
# by length now that they align (the state census for the form).
INIHIGH4=${INIHIGH4:-12}; BFAC4=${BFAC4:--200}
K3D2=${K3D2:-4}; ITER3D2=${ITER3D2:-25}; T3D2=${T3D2:-4}
LAST3D2=$(printf 'run_it%03d' "$ITER3D2")

do_mask4() {
  mkdir -p Refine4
  local thr; thr=$(python3 -I "$HERE/mask_threshold.py" Refine3/run_class001.mrc)
  echo "solvent mask threshold $thr"
  relion_mask_create --i Refine3/run_class001.mrc --o Refine4/solvent_mask.mrc --lowpass 15 \
    --ini_threshold "$thr" --extend_inimask 4 --width_soft_edge 8 --angpix "$APIXR"
}

