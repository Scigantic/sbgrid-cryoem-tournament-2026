#!/usr/bin/env bash
# Rod pass. The blob picks of the first chunk job showed the specimen is short rods
# (about 50 A wide, a 40 A repeat along the axis, 150-400 A long, variable length) and
# the submission form asks how many oligomeric states there are. So: pick the rods as
# filaments with three rod class averages as templates, count the repeats in each rod
# (the census), extract one big box per whole rod and classify those, so classes show
# rods of 4, 5, 6... repeats side by side. Needs CtfFind/ and Class2D/ from the first
# job and the corrected micrographs (MotionCorr/Movies, regenerated by the caller).
source "$(dirname "$0")/common.sh"
cd "$PROJ"
RODS_CLASSES=${RODS_CLASSES:-23,17,5}   # rod classes of Class2D/run_it012 used as templates
CLASS_ITER=${CLASS_ITER:-run_it012}
TUBE_D=${TUBE_D:-80}                    # rod outer diameter, A (generous: measured 50-65)
RISE=${RISE:-40}                        # repeat along the rod, A; also the segment spacing
RODBOX_A=${RODBOX_A:-500}               # box for a whole rod, A (longest rods seen ~400)
RODSCALE=${RODSCALE:-80}                # box after binning, px
N2DR=${N2DR:-20000}; K2DR=${K2DR:-40}; ITER2DR=${ITER2DR:-12}
ANGPIX_REF=${ANGPIX_REF:-$(awk -v a="$ANGPIX" 'BEGIN{printf "%.4f", a*4}')}  # Extract4 was bin 4
BOX=$(awk -v a="$ANGPIX" -v b="$RODBOX_A" 'BEGIN{printf "%d", int(b/a/2)*2}')
RODDIAM=$(awk -v b="$RODBOX_A" 'BEGIN{printf "%d", b*0.9}')
LASTR=$(printf 'run_it%03d' "$ITER2DR")

do_templates() {
  { printf '\ndata_\n\nloop_\n_rlnReferenceImage #1\n'
    for c in ${RODS_CLASSES//,/ }; do echo "$c@Class2D/${CLASS_ITER}_classes.mrcs"; done
  } > rod_templates.star
  echo "templates: $RODS_CLASSES at $ANGPIX_REF A/px"
}

do_pickrods() {
  mkdir -p AutoPickRods
  # one rank per GPU (the leader also picks); shrink 0.5 is the minimum RELION advises for helices
  $MPI -np "$NGPU" relion_autopick_mpi --i CtfFind/micrographs_ctf.star --odir AutoPickRods/ \
    --pickname autopick --ref rod_templates.star --angpix_ref "$ANGPIX_REF" --ang 5 --lowpass 20 \
    --particle_diameter "$DIAM" --shrink 0.5 --threshold "${RODS_THRESH:-0.25}" \
    --min_distance "$RISE" --max_stddev_noise 1.1 --gpu "$GPUARG" \
    --helix --helical_tube_outer_diameter "$TUBE_D" --helical_tube_length_min "${TUBE_MIN:-100}" \
    --helical_tube_kappa_max 0.25
}

do_census() {
  python3 -I "$HERE/rods.py" AutoPickRods/autopick.star "$RISE" RodsPick | tee RodsPick_census.txt
}

do_extractrods() {
  mkdir -p ExtractRods
  # black_dust: the ice blobs are many sigma dark; dust removal runs before the contrast
  # inversion, so this replaces them with noise and keeps them out of the class averages.
  $MPI -np "$NCPU" relion_preprocess_mpi --i CtfFind/micrographs_ctf.star \
    --coord_list RodsPick/rods.star --part_star ExtractRods/particles.star \
    --part_dir ExtractRods/ --extract --extract_size "$BOX" --scale "$RODSCALE" --norm \
    --bg_radius $((RODSCALE * 3 / 8)) --white_dust -1 --black_dust "${BLACK_DUST:-5}" --invert_contrast
  echo "rods extracted: $(nparticles ExtractRods/particles.star), box $BOX px scaled to $RODSCALE"
}

do_subsetrods() {
  mkdir -p Class2DRods
  local total; total=$(nparticles ExtractRods/particles.star)
  if ((N2DR >= total)); then
    cp ExtractRods/particles.star Class2DRods/input.star
  else
    relion_star_handler --i ExtractRods/particles.star --o Class2DRods/split --split \
      --random_order --random_seed 1 --size_split "$N2DR" > /dev/null
    cp Class2DRods/split_split1. Class2DRods/input.star
  fi
  echo "2D input: $(nparticles Class2DRods/input.star) of $total rods"
}

do_class2drods() {
  $MPI -np "$NP_GPU" relion_refine_mpi --i Class2DRods/input.star --o Class2DRods/run \
    --K "$K2DR" --iter "$ITER2DR" --tau2_fudge 2 --particle_diameter "$RODDIAM" --flatten_solvent \
    --zero_mask --center_classes --oversampling 1 --psi_step 6 --offset_range 8 \
    --offset_step 2 --norm --scale --dont_combine_weights_via_disc --pool 30 --pad 2 \
    --ctf --j "$THREADS_GPU" --gpu "$GPUARG" --preread_images
}

do_viewrods() {
  python3 -I "$HERE/view_classes.py" "Class2DRods/${LASTR}_model.star" \
    "Class2DRods/${LASTR}_classes.mrcs" Class2DRods/top_classes.jpg 40
}

# Second round on the rod classes only. The first round put 61% of the rods in one
# class and gave 30 classes to ice blobs, so the lengths did not separate. Keep the
# rod classes (SEL_CLASSES, read off top_classes.jpg), classify again with more
# classes, a sharper tau2 and a tighter mask, so rods of different length part ways.
SEL_CLASSES=${SEL_CLASSES:-17,3,33,13,8,24,11,36,16,19}
K2DS=${K2DS:-60}; ITER2DS=${ITER2DS:-20}; T2DS=${T2DS:-4}; SELDIAM=${SELDIAM:-360}
LASTS=$(printf 'run_it%03d' "$ITER2DS")

do_selrods() {
  mkdir -p Class2DSel
  python3 -I "$HERE/select_classes.py" "Class2DRods/${LASTR}_data.star" \
    Class2DSel/input.star "$SEL_CLASSES"
}

do_class2dsel() {
  $MPI -np "$NP_GPU" relion_refine_mpi --i Class2DSel/input.star --o Class2DSel/run \
    --K "$K2DS" --iter "$ITER2DS" --tau2_fudge "$T2DS" --particle_diameter "$SELDIAM" \
    --flatten_solvent --zero_mask --center_classes --oversampling 1 --psi_step 4 \
    --offset_range 6 --offset_step 2 --norm --scale --dont_combine_weights_via_disc \
    --pool 30 --pad 2 --ctf --j "$THREADS_GPU" --gpu "$GPUARG" --preread_images
}

do_viewsel() {
  python3 -I "$HERE/view_classes.py" "Class2DSel/${LASTS}_model.star" \
    "Class2DSel/${LASTS}_classes.mrcs" Class2DSel/top_classes.jpg "$K2DS"
}

# Third round: 3D. Per-particle bead counting on the 2D alignments is below the noise
# floor (rodlen2.py: median margin 0.013), so the length states are separated where
# RELION pools the evidence over the whole population: a 3D classification seeded from
# synthetic rods of 3..7 beads (the repeat is known), low-passed to 25 A so only the
# bead count carries weight. Class occupancies are the census; view3d.py renders and
# measures each class volume. A de novo initial model (DO_INI=1) took 85 min for
# K=5 on a g4dn node and timed out; the synthetic seeds skip it.
ROD3D_CLASSES=${ROD3D_CLASSES:-3,56,29,54,19}   # rod classes of Class2DSel/run_it020
BEADS=${BEADS:-3,4,5,6,7}; BEAD_D=${BEAD_D:-50}
K3D=$(awk -F, '{print NF}' <<< "$BEADS"); ITERINI=${ITERINI:-150}; ITER3D=${ITER3D:-25}; T3D=${T3D:-4}
DIAM3D=${DIAM3D:-360}
APIX3D=$(awk -v a="$ANGPIX" -v b="$BOX" -v s="$RODSCALE" 'BEGIN{printf "%.4f", a*b/s}')
LASTI=$(printf 'run_it%03d' "$ITERINI"); LAST3D=$(printf 'run_it%03d' "$ITER3D")

do_sel3d() {
  mkdir -p Rod3D
  python3 -I "$HERE/select_classes.py" "Class2DSel/${LASTS}_data.star" \
    Rod3D/input.star "$ROD3D_CLASSES"
}

do_ini3d() {
  mkdir -p Rod3D/Ini
  # gradient (VDAM) initial model, no MPI; the threads share the GPUs
  relion_refine --i Rod3D/input.star --o Rod3D/Ini/run --denovo_3dref --grad \
    --iter "$ITERINI" --K "$K3D" --sym C1 --ctf --particle_diameter "$DIAM3D" \
    --flatten_solvent --zero_mask --dont_combine_weights_via_disc --pool 30 --pad 1 \
    --skip_gridding --oversampling 1 --healpix_order 1 --offset_range 6 --offset_step 2 \
    --auto_sampling --tau2_fudge 4 --grad_write_iter 10 --j "$NCPU" --gpu "$GPUARG" \
    --preread_images
}

do_viewini() {
  python3 -I "$HERE/view3d.py" "Rod3D/Ini/${LASTI}_model.star" Rod3D/Ini/classes.jpg "$RISE"
}

do_refs3d() {
  python3 -I "$HERE/make_rod_refs.py" Rod3D/Refs "$RODSCALE" "$APIX3D" "$BEAD_D" "$RISE" "$BEADS"
}

do_class3d() {
  mkdir -p Rod3D/Cls
  local refs=Rod3D/Refs/refs.star
  if [[ -n "${DO_INI:-}" ]]; then
    { printf '\ndata_\n\nloop_\n_rlnReferenceImage #1\n'
      for ((k = 1; k <= K3D; k++)); do printf 'Rod3D/Ini/%s_class%03d.mrc\n' "$LASTI" "$k"; done
    } > Rod3D/refs_ini.star
    refs=Rod3D/refs_ini.star
  fi
  $MPI -np "$NP_GPU" relion_refine_mpi --i Rod3D/input.star --o Rod3D/Cls/run \
    --ref "$refs" --firstiter_cc --ini_high 25 --ctf --iter "$ITER3D" \
    --tau2_fudge "$T3D" --particle_diameter "$DIAM3D" --K "$K3D" --flatten_solvent \
    --zero_mask --oversampling 1 --healpix_order 2 --offset_range 6 --offset_step 2 \
    --sym C1 --norm --scale --dont_combine_weights_via_disc --pool 30 --pad 2 \
    --j "$THREADS_GPU" --gpu "$GPUARG" --preread_images
}

do_view3d() {
  python3 -I "$HERE/view3d.py" "Rod3D/Cls/${LAST3D}_model.star" Rod3D/Cls/classes.jpg "$RISE"
}


# Tails: the picker length is biased short by ~37 A but tracks the class-average extents,
# so it is a usable prior. Classify the shortest and the longest rods separately; a class
# average is the high-signal detector, so 2-3 bead and 6-8 bead rods, if they exist, show
# up as their own averages instead of being absorbed into the 4-bead classes.
SHORT_MAX=${SHORT_MAX:-85}; LONG_MIN=${LONG_MIN:-165}
KT=${KT:-20}; ITERT=${ITERT:-20}
LASTT=$(printf 'run_it%03d' "$ITERT")

do_seltails() {
  mkdir -p Class2DShort Class2DLong
  python3 -I "$HERE/select_by_length.py" ExtractRods/particles.star Class2DShort/input.star 0 "$SHORT_MAX"
  python3 -I "$HERE/select_by_length.py" ExtractRods/particles.star Class2DLong/input.star "$LONG_MIN" 9999
}

class2d_tail() {  # DIR DIAM
  $MPI -np "$NP_GPU" relion_refine_mpi --i "$1/input.star" --o "$1/run" \
    --K "$KT" --iter "$ITERT" --tau2_fudge "$T2DS" --particle_diameter "$2" \
    --flatten_solvent --zero_mask --center_classes --oversampling 1 --psi_step 4 \
    --offset_range 6 --offset_step 2 --norm --scale --dont_combine_weights_via_disc \
    --pool 30 --pad 2 --ctf --j "$THREADS_GPU" --gpu "$GPUARG" --preread_images
  python3 -I "$HERE/view_classes.py" "$1/${LASTT}_model.star" "$1/${LASTT}_classes.mrcs" \
    "$1/top_classes.jpg" "$KT"
}
do_class2dshort() { class2d_tail Class2DShort 300; }
do_class2dlong() { class2d_tail Class2DLong 450; }


# Resolution gate: refine the main rod population at bin 2 on this chunk. The 3D
# classification could not sort lengths, but it did isolate the particles with a second
# object in the box (REF_CLASSES excludes that class). Re-extract those from the 3D poses
# in a tighter box, refine from the cleanest consensus volume, mask, post-process.
REF_CLASSES=${REF_CLASSES:-1,2,3,4}; REF_CLASS=${REF_CLASS:-2}
REFBOX_A=${REFBOX_A:-300}; REFBIN=${REFBIN:-2}; REFDIAM=${REFDIAM:-220}
RBOX=$(awk -v a="$ANGPIX" -v b="$REFBOX_A" 'BEGIN{printf "%d", int(b/a/2)*2}')
RSCALE=$(( RBOX / REFBIN / 2 * 2 ))
APIXR=$(awk -v a="$ANGPIX" -v b="$RBOX" -v s="$RSCALE" 'BEGIN{printf "%.4f", a*b/s}')

do_selref() {
  mkdir -p Refine2
  python3 -I "$HERE/select_classes.py" "Rod3D/Cls/${LAST3D}_data.star" Refine2/sel.star "$REF_CLASSES"
}

do_extract2() {
  mkdir -p Extract2
  $MPI -np "$NCPU" relion_preprocess_mpi --i CtfFind/micrographs_ctf.star \
    --reextract_data_star Refine2/sel.star --recenter --part_star Extract2/particles.star \
    --part_dir Extract2/ --extract --extract_size "$RBOX" --scale "$RSCALE" --norm \
    --bg_radius $((RSCALE * 3 / 8)) --white_dust -1 --black_dust "${BLACK_DUST:-5}" --invert_contrast
  echo "re-extracted $(nparticles Extract2/particles.star) particles, box $RBOX px -> $RSCALE px at $APIXR A/px"
}

do_ref2() {
  relion_image_handler --i "Rod3D/Cls/${LAST3D}_class$(printf '%03d' "$REF_CLASS").mrc" \
    --angpix "$APIX3D" --rescale_angpix "$APIXR" --new_box "$RSCALE" --o Refine2/ref.mrc
}

do_refine2() {
  # resume an interrupted run (iterations synced to EFS by hand) from its last optimiser file
  local opt; opt=$(ls -t Refine2/run_it*_optimiser.star 2>/dev/null | head -1 || true)
  if [[ -n "$opt" && ! -s Refine2/run_class001.mrc ]]; then
    echo "continuing refinement from $opt"
    $MPI -np "$NP_GPU" relion_refine_mpi --continue "$opt" --o Refine2/run \
      --dont_combine_weights_via_disc --pool 30 --j "$THREADS_GPU" --gpu "$GPUARG" --preread_images
    return
  fi
  $MPI -np "$NP_GPU" relion_refine_mpi --i Extract2/particles.star --o Refine2/run \
    --auto_refine --split_random_halves --ref Refine2/ref.mrc --trust_ref_size --ini_high 30 \
    --dont_combine_weights_via_disc --pool 30 --pad 2 --ctf --particle_diameter "$REFDIAM" \
    --flatten_solvent --zero_mask --oversampling 1 --healpix_order 2 \
    --auto_local_healpix_order 4 --offset_range 5 --offset_step 2 --sym C1 \
    --low_resol_join_halves 40 --norm --scale --j "$THREADS_GPU" --gpu "$GPUARG" --preread_images
}

do_post2() {
  mkdir -p Refine2/Post
  local thr; thr=$(python3 -I "$HERE/mask_threshold.py" Refine2/run_class001.mrc)
  echo "mask threshold $thr"
  relion_mask_create --i Refine2/run_class001.mrc --o Refine2/Post/mask.mrc --lowpass 15 \
    --ini_threshold "$thr" --extend_inimask 3 --width_soft_edge 6 --angpix "$APIXR"
  relion_postprocess --i Refine2/run_half1_class001_unfil.mrc --mask Refine2/Post/mask.mrc \
    --angpix "$APIXR" --auto_bfac --autob_lowres 10 --o Refine2/Post/postprocess
  grep -i "FINAL RESOLUTION\|BFACTOR" Refine2/Post/postprocess.log || true
  echo "RESULT Refine2: $(grep -h '_rlnFinalResolution\|_rlnBfactorUsedForSharpening' Refine2/Post/postprocess.star | tr -s ' ' | tr '\n' ' ')"
  python3 -I "$HERE/view3d.py" Refine2/run_model.star Refine2/map.jpg "$RISE"
}


# Breaking the rod's pseudo-symmetry. The bin-2 auto-refine from a 30 A low-passed
# consensus converged at 15 A: at that resolution a beaded rod is nearly cylindrical and
# periodic, so the rotation about its axis and the shift by one bead are undetermined and
# the refinement cannot climb. Three cheap steps on the same 13.5k clean particles:
# a 2D classification at bin 2 (do higher-resolution features exist in projection?),
# a gradient de novo model (VDAM breaks the symmetry itself), then an auto-refine from
# that model with a 15 A starting low-pass.
K2D2=${K2D2:-40}; ITER2D2=${ITER2D2:-25}
ITERINI2=${ITERINI2:-150}; INIHIGH3=${INIHIGH3:-15}
LAST2D2=$(printf 'run_it%03d' "$ITER2D2"); LASTI2=$(printf 'run_it%03d' "$ITERINI2")

